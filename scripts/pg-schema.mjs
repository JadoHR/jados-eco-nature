// Generates prisma/postgres/schema.prisma from prisma/schema.prisma.
//
// prisma/schema.prisma (SQLite) is the single source of truth for the data model and is
// used for local development and tests. Production (Vercel + Neon) uses the Postgres copy,
// which differs only in its datasource block. Run `npm run db:pg:schema` after editing the
// model, then `npm run db:pg:migration -- <name>` to create the matching Postgres migration.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(path.join(root, "prisma", "schema.prisma"), "utf8");

const datasource = /datasource db \{[^}]*\}/;
if (!datasource.test(src)) throw new Error("datasource block not found in prisma/schema.prisma");

export const pgSchema =
  "// GENERATED by scripts/pg-schema.mjs from prisma/schema.prisma — do not edit by hand.\n" +
  src.replace(
    datasource,
    `datasource db {
  provider  = "postgresql"
  url       = env("DATABASE_URL")
  // Neon's direct (non-pooled) connection, used by migrations. Falls back to DATABASE_URL in scripts/vercel-build.mjs.
  directUrl = env("DATABASE_URL_UNPOOLED")
}`,
  );

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  mkdirSync(path.join(root, "prisma", "postgres"), { recursive: true });
  writeFileSync(path.join(root, "prisma", "postgres", "schema.prisma"), pgSchema);
  console.log("Wrote prisma/postgres/schema.prisma");
}
